#!/usr/bin/env python3
"""Generate the packaged agent-conventions schema and model mirror.

Run from any directory with ``python3 scripts/sync_agent_conventions.py``;
use ``--check`` to report drift without writing files. Requires Python 3.10+.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = ROOT / "claude" / "shared"
SOURCE_SCHEMAS = SOURCE_ROOT / "schemas" / "v1.0"
MIRROR_ROOT = ROOT / "scripts" / "dontpanic_orchestrate" / "agent_conventions"
HEADER = "# Generated by scripts/sync_agent_conventions.py from claude/shared; do not edit by hand."
_ENCODING_COOKIE = re.compile(r"coding[:=][ \t]*[-\w.]+")

_INIT_PATHS = (
    "__init__.py",
    "schemas/__init__.py",
    "schemas/v1_0/__init__.py",
    "schemas/v1_0/models/__init__.py",
)
_INIT_CONTENT = b'"""Generated by scripts/sync_agent_conventions.py from claude/shared; do not edit by hand."""\n'


def _mapped_from(module: str | None) -> tuple[int, str | None] | None:
    """Return the relative-import level and module for mirrored model imports."""
    if module == "models":
        return 1, None
    if module and module.startswith("models."):
        return 1, module.removeprefix("models.")
    if module == "experience_readiness":
        return 1, module
    return None


def _from_signature(node: ast.ImportFrom) -> tuple[int, str | None, tuple[tuple[str, str | None], ...]]:
    mapped = _mapped_from(node.module) if node.level == 0 else None
    level, module = mapped if mapped is not None else (node.level, node.module)
    return level, module, tuple((alias.name, alias.asname) for alias in node.names)


def _replace_from_line(line: str, node: ast.ImportFrom) -> str:
    mapped = _mapped_from(node.module) if node.level == 0 else None
    if mapped is None:
        return line
    level, module = mapped
    old = f"from {node.module}"
    new = f"from {'.' * level}{module}" if module else f"from {'.' * level}"
    return line.replace(old, new, 1)


def _import_replacement(node: ast.Import, line: str) -> str | None:
    """Rewrite absolute model imports while preserving their local binding."""
    indent = line[: len(line) - len(line.lstrip())]
    trailing = ""
    comment_index = line.find("#")
    if comment_index >= 0:
        trailing = "  " + line[comment_index:].rstrip("\r\n")

    statements: list[str] = []
    changed = False
    for alias in node.names:
        if alias.name == "experience_readiness":
            statement = "from . import experience_readiness"
            if alias.asname:
                statement += f" as {alias.asname}"
            changed = True
        elif alias.name.startswith("models."):
            changed = True
            parent, _, leaf = alias.name.rpartition(".")
            if alias.asname:
                statement = f"from .{parent} import {leaf} as {alias.asname}"
                statements.append(indent + statement)
            else:
                # Import the submodule and bind its package, matching
                # ``import models.X``'s ``models.X`` lookup behavior.
                statements.append(indent + f"from .{parent} import {leaf}")
                statements.append(indent + "from . import models")
            continue
        else:
            statement = f"import {alias.name}"
            if alias.asname:
                statement += f" as {alias.asname}"
        statements.append(indent + statement)

    if not changed:
        return None
    if trailing:
        statements[-1] += trailing
    return "\n".join(statements)


def _rewrite_imports(source: str, relative_path: str) -> str:
    """Rewrite only schema-model imports, collapsing equivalent fallbacks."""
    tree = ast.parse(source, filename=relative_path)
    lines = source.splitlines(keepends=True)
    replacements: list[tuple[int, int, str]] = []
    collapsed_ranges: list[tuple[int, int]] = []

    for node in ast.walk(tree):
        if not isinstance(node, ast.Try) or len(node.body) != 1 or len(node.handlers) != 1:
            continue
        handler = node.handlers[0]
        if (
            node.orelse
            or node.finalbody
            or not isinstance(node.body[0], ast.ImportFrom)
            or not isinstance(handler.type, ast.Name)
            or handler.type.id != "ImportError"
            or len(handler.body) != 1
            or not isinstance(handler.body[0], ast.ImportFrom)
        ):
            continue
        primary = node.body[0]
        fallback = handler.body[0]
        if _from_signature(primary) != _from_signature(fallback):
            continue
        primary_lines = lines[primary.lineno - 1 : (primary.end_lineno or primary.lineno)]
        primary_lines[0] = _replace_from_line(primary_lines[0].rstrip("\r\n"), primary)
        try_line = lines[node.lineno - 1]
        try_indent = len(try_line) - len(try_line.lstrip())
        import_indent = len(primary_lines[0]) - len(primary_lines[0].lstrip())
        dedent = max(import_indent - try_indent, 0)
        normalized_lines = [
            line[dedent:] if line.strip() and line[:dedent].isspace() else line
            for line in primary_lines
        ]
        replacement = "".join(normalized_lines).rstrip("\r\n")
        replacements.append((node.lineno, node.end_lineno or node.lineno, replacement))
        collapsed_ranges.append((node.lineno, node.end_lineno or node.lineno))

    def is_collapsed(lineno: int) -> bool:
        return any(start <= lineno <= end for start, end in collapsed_ranges)

    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and not is_collapsed(node.lineno):
            line = lines[node.lineno - 1].rstrip("\r\n")
            replacement = _replace_from_line(line, node)
            if replacement != line:
                replacements.append((node.lineno, node.lineno, replacement))
        elif isinstance(node, ast.Import) and not is_collapsed(node.lineno):
            start = node.lineno - 1
            end = node.end_lineno or node.lineno
            statement = _import_replacement(node, "".join(lines[start:end]).rstrip("\r\n"))
            if statement is not None:
                replacements.append((node.lineno, end, statement))

    for start, end, replacement in sorted(replacements, reverse=True):
        start_index = start - 1
        end_index = end
        ending = "\r\n" if lines[start_index].endswith("\r\n") else "\n"
        lines[start_index:end_index] = [part + ending for part in replacement.split("\n")]
    return "".join(lines)


def _with_header(source: str) -> str:
    """Add the generated marker after a shebang/encoding cookie, if present."""
    lines = source.splitlines(keepends=True)
    insertion = 1 if lines and lines[0].startswith("#!") else 0
    for index in range(min(2, len(lines))):
        if _ENCODING_COOKIE.search(lines[index]):
            insertion = max(insertion, index + 1)
    newline = "\r\n" if lines and lines[0].endswith("\r\n") else "\n"
    lines.insert(insertion, HEADER + newline)
    return "".join(lines)


def expected_files() -> dict[str, bytes]:
    """Build the exact generated file tree in memory."""
    files = {relative: _INIT_CONTENT for relative in _INIT_PATHS}
    files["VERSION"] = (SOURCE_ROOT / "VERSION").read_bytes()

    for schema_path in sorted(SOURCE_SCHEMAS.glob("*.schema.json")):
        files[f"schemas/v1_0/{schema_path.name}"] = schema_path.read_bytes()

    model_dir = SOURCE_SCHEMAS / "models"
    for model_path in sorted(model_dir.glob("*.py")):
        if model_path.name == "__init__.py":
            continue
        relative = f"schemas/v1_0/models/{model_path.name}"
        source = model_path.read_bytes().decode("utf-8")
        mirrored = _with_header(_rewrite_imports(source, relative))
        files[relative] = mirrored.encode("utf-8")
    return files


def _disk_files() -> dict[str, Path]:
    found: dict[str, Path] = {}
    if not MIRROR_ROOT.exists():
        return found
    for path in MIRROR_ROOT.rglob("*"):
        relative = path.relative_to(MIRROR_ROOT)
        if "__pycache__" in relative.parts or not path.is_file():
            continue
        found[relative.as_posix()] = path
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing files")
    args = parser.parse_args(argv)

    try:
        expected = expected_files()
    except (OSError, SyntaxError, UnicodeError) as exc:
        print(f"Could not generate agent-conventions mirror: {exc}", file=sys.stderr)
        return 2

    current = _disk_files()
    drift = sorted(
        relative
        for relative in set(expected) | set(current)
        if relative not in expected
        or relative not in current
        or current[relative].read_bytes() != expected.get(relative)
    )
    if args.check:
        for relative in drift:
            print(f"agent_conventions/{relative}", file=sys.stderr)
        return 1 if drift else 0

    for relative in sorted(set(current) - set(expected)):
        current[relative].unlink()
    for relative, content in expected.items():
        path = MIRROR_ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_bytes() != content:
            path.write_bytes(content)
            print(f"agent_conventions/{relative}")

    if MIRROR_ROOT.exists():
        for directory in sorted(
            (path for path in MIRROR_ROOT.rglob("*") if path.is_dir()),
            key=lambda path: len(path.parts),
            reverse=True,
        ):
            if not any(directory.iterdir()):
                directory.rmdir()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
